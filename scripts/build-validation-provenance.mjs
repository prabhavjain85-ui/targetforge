#!/usr/bin/env node
/**
 * Generates src/shared/validationProvenance.js from the fitted weights asset.
 *
 * The validation page used to carry a hand-typed commit constant. It said
 * "9406739" — the commit that committed the benchmark outputs — while the
 * weights file named 7883506 as the producing commit and carried a run
 * timestamp earlier than both. A reader had no way to tell which commit
 * actually produced the numbers.
 *
 * Deriving the provenance from the weights file at build time removes the
 * possibility of disagreement: there is now one place the facts live, and
 * src/methodologyProvenance.test.js re-runs this derivation and fails if the
 * committed output has drifted from it.
 *
 * CRA will not bundle anything outside src/, which is what keeps server/ off
 * the client, so the values are copied into src/ rather than imported across
 * that boundary.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const WEIGHTS_PATH = path.join(repoRoot, "server", "data", "novelty", "fitted-simplex-weights.json");
const OUT_PATH = path.join(repoRoot, "src", "shared", "validationProvenance.js");

/** Shared with the provenance test, so both derive identically. */
export function deriveProvenance(weights) {
  const p = weights.provenance || {};
  const missing = ["generator", "generatedAt", "producedByCommit"].filter((k) => !p[k]);
  if (missing.length) {
    throw new Error(`fitted-simplex-weights.json provenance is missing: ${missing.join(", ")}`);
  }
  return {
    generator: p.generator,
    generatedAt: p.generatedAt,
    producedByCommit: p.producedByCommit,
    sourceFiles: p.sourceFiles || [],
  };
}

export function renderModule(prov) {
  const json = (v) => JSON.stringify(v, null, 2).replace(/\n/g, "\n");
  return `/**
 * GENERATED FILE — do not edit.
 *
 * Written by scripts/build-validation-provenance.mjs from
 * server/data/novelty/fitted-simplex-weights.json. Run
 * \`npm run build:validation-provenance\` after refitting the model.
 *
 * These describe the run that produced every figure on the validation page.
 * The generator path and run timestamp come from the weights file itself, so
 * the page cannot quote a commit that disagrees with the asset it ships.
 */

/** Script that produced the figures quoted on the validation page. */
export const VALIDATION_GENERATOR = ${JSON.stringify(prov.generator)};

/** When that script last ran, ISO-8601, from the weights asset. */
export const VALIDATION_GENERATED_AT = ${JSON.stringify(prov.generatedAt)};

/** Commit of the working tree that ran the generator. */
export const VALIDATION_PRODUCED_BY_COMMIT = ${JSON.stringify(prov.producedByCommit)};

/** Artifacts the generator wrote, which the page cites per section. */
export const VALIDATION_SOURCE_FILES = ${json(prov.sourceFiles)};

/** Short commit, for display. */
export const VALIDATION_COMMIT_SHORT = ${JSON.stringify(prov.producedByCommit.slice(0, 7))};

/** One line naming the run, for the page footer. */
export const VALIDATION_RUN_LINE =
  ${JSON.stringify(
    `Generated by ${prov.generator} at ${prov.generatedAt} from commit ${prov.producedByCommit.slice(0, 7)}.`
  )};
`;
}

function main() {
  // --check verifies the committed file is current without writing, so a test
  // can assert it by running the real generator rather than reimplementing it.
  const check = process.argv.includes("--check");
  const weights = JSON.parse(fs.readFileSync(WEIGHTS_PATH, "utf8"));
  const text = renderModule(deriveProvenance(weights));
  const existing = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, "utf8") : null;
  // Normalise line endings so a CRLF checkout does not look like a change.
  const current = existing !== null && existing.replace(/\r\n/g, "\n") === text;

  if (check) {
    if (current) {
      process.stderr.write("[validation-provenance] current\n");
      return;
    }
    process.stderr.write(
      `[validation-provenance] STALE: ${path.relative(repoRoot, OUT_PATH)} does not match ` +
        `${path.relative(repoRoot, WEIGHTS_PATH)}. Run: npm run build:validation-provenance\n`
    );
    process.exitCode = 1;
    return;
  }

  if (current) {
    process.stderr.write("[validation-provenance] already current\n");
    return;
  }
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, text);
  process.stderr.write(`[validation-provenance] wrote ${path.relative(repoRoot, OUT_PATH)}\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main();
}
